"""Load the raw Olist CSVs into DuckDB, build the star schema and run data-quality checks.

Runs sql/01_*.sql ... sql/04_*.sql in order, then writes reports/data_quality.md.
Fails if any blocking data-quality check finds problems.
"""
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
DB = ROOT / "warehouse" / "olist.duckdb"
REPORT = ROOT / "reports" / "data_quality.md"

TABLES = ["fact_orders", "fact_order_items", "dim_date", "dim_customer",
          "dim_seller", "dim_product", "stg_reviews_raw", "stg_payments"]


def main():
    missing = [p.name for p in [RAW / "olist_orders_dataset.csv"] if not p.exists()]
    assert not missing, "Raw data missing - run scripts/download_data.py first"

    DB.parent.mkdir(exist_ok=True)
    DB.unlink(missing_ok=True)  # always rebuild from scratch
    con = duckdb.connect(str(DB))

    for sql_file in sorted((ROOT / "sql").glob("0*.sql")):
        print(f"running {sql_file.name}")
        con.execute(sql_file.read_text().replace("{raw}", RAW.as_posix()))

    counts = {t: con.sql(f"SELECT COUNT(*) FROM {t}").fetchone()[0] for t in TABLES}
    checks = con.sql("SELECT severity, check_name, rows_affected FROM dq_results").fetchall()
    con.close()

    lines = ["# Data quality report", "",
             "Generated by `scripts/build_warehouse.py`. Blocking checks must be 0 or the build fails;",
             "warnings are known source issues that the KPI queries handle explicitly.", "",
             "## Table row counts", "", "| Table | Rows |", "|---|---:|"]
    lines += [f"| {t} | {n:,} |" for t, n in counts.items()]
    lines += ["", "## Checks", "", "| Severity | Check | Rows affected | Status |", "|---|---|---:|---|"]
    for severity, name, n in checks:
        status = "PASS" if n == 0 else ("FAIL" if severity == "blocking" else "noted")
        lines.append(f"| {severity} | {name} | {n:,} | {status} |")
    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text("\n".join(lines) + "\n")
    print(f"wrote {REPORT.relative_to(ROOT)}")

    failed = [name for severity, name, n in checks if severity == "blocking" and n]
    assert not failed, f"Blocking data-quality checks failed: {failed}"


if __name__ == "__main__":
    main()
