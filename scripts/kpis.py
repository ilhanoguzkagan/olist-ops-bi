"""Run every KPI query in sql/kpis/ against the warehouse.

Shared by the dashboard and Excel export so all outputs use identical numbers.
Running this file directly saves each KPI as CSV in reports/kpis/.
"""
from pathlib import Path

import duckdb
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "warehouse" / "olist.duckdb"
KPI_DIR = ROOT / "sql" / "kpis"


def load_kpis() -> dict[str, pd.DataFrame]:
    """Return {query name without number prefix: result DataFrame}, e.g. 'monthly_trend'."""
    assert DB.exists(), "Warehouse missing - run scripts/build_warehouse.py first"
    with duckdb.connect(str(DB), read_only=True) as con:
        return {f.stem.split("_", 1)[1]: con.sql(f.read_text()).df()
                for f in sorted(KPI_DIR.glob("*.sql"))}


def findings(k: dict[str, pd.DataFrame]) -> list[tuple[str, str]]:
    """Headline findings as (title, sentence) pairs, every number taken from the KPI results."""
    h = k["headline"].iloc[0]
    rev = k["review_vs_lateness"]
    late_rev = rev[rev.lateness_bucket != "0. On time"]
    stages = k["lead_time_components"].set_index("delivery_outcome")
    cause = k["late_root_cause"].set_index("handover")
    on_time_handover = cause.loc["Seller handed over on time"]
    missed_handover = cause.loc["Seller missed hand-over deadline"]
    worst_months = k["monthly_trend"].nsmallest(3, "on_time_rate").sort_values("year_month")
    lanes = k["lane_performance"]
    big_weak_lane = lanes[lanes.on_time_rate < h.on_time_rate].nlargest(1, "orders").iloc[0]
    states = k["customer_state"].query("orders >= 300").nsmallest(2, "on_time_rate")
    sellers = k["seller_scorecard"]
    tier_c = sellers[sellers.tier.str.startswith("C")]
    repeat = k["repeat_by_first_experience"].set_index("first_order_experience").repeat_rate

    pct = lambda x: f"{x:.1%}"
    return [
        ("Delivery promises are padded",
         f"{pct(h.on_time_rate)} of {h.orders_delivered:,.0f} delivered orders arrived on or before the promised date, "
         f"but customers were promised {h.avg_promised_days:.1f} days on average while the median delivery took "
         f"{h.median_lead_time_days:.1f} days (90th percentile {h.p90_lead_time_days:.1f})."),
        ("Late deliveries drive negative reviews",
         f"Average rating falls from {h.avg_review_on_time:.2f} (on time) to {h.avg_review_late:.2f} (late). "
         f"Late orders are {pct(late_rev.share_of_orders.sum())} of reviewed orders but produce "
         f"{pct(late_rev.share_of_negative_reviews.sum())} of all 1-2 star reviews."),
        ("Carrier transit is the main source of delay",
         f"Late orders spent {stages.loc['Late', 'carrier_transit_days']:.1f} days in carrier transit vs "
         f"{stages.loc['On time', 'carrier_transit_days']:.1f} for on-time orders, and "
         f"{pct(on_time_handover.share_of_all_late_orders)} of late orders had been handed to the carrier on time. "
         f"Orders where the seller missed the hand-over deadline were still "
         f"{missed_handover.late_rate / on_time_handover.late_rate:.1f}x as likely to arrive late "
         f"({pct(missed_handover.late_rate)} vs {pct(on_time_handover.late_rate)})."),
        ("Peak periods break the network",
         "On-time rate fell to " + ", ".join(f"{pct(r.on_time_rate)} in {r.year_month}" for r in worst_months.itertuples())
         + f" against {pct(h.on_time_rate)} for the whole period."),
        ("Problems concentrate in a few lanes and states",
         f"The largest below-average lane is {big_weak_lane.lane} ({big_weak_lane.orders:,.0f} orders, "
         f"{pct(big_weak_lane.on_time_rate)} on time). The weakest destination states are "
         + " and ".join(f"{r.customer_state} ({pct(r.on_time_rate)})" for r in states.itertuples()) + "."),
        ("A small seller group needs an improvement plan",
         f"{len(tier_c)} of {len(sellers)} sellers with 50+ orders fall below 85% on time or a 3.8 rating; "
         f"they account for {pct(tier_c.gmv_brl.sum() / sellers.gmv_brl.sum())} of scorecard GMV."),
        ("Late first orders reduce repeat purchases slightly",
         f"Repeat purchase rate is {pct(repeat['First order late'])} after a late first delivery vs "
         f"{pct(repeat['First order on time'])} after an on-time one (repeat buying is rare on this marketplace overall)."),
    ]


def main():
    out = ROOT / "reports" / "kpis"
    out.mkdir(parents=True, exist_ok=True)
    k = load_kpis()
    for name, df in k.items():
        assert not df.empty, f"KPI {name} returned no rows"
        df.round(6).to_csv(out / f"{name}.csv", index=False)  # rounding hides float-summation noise between runs
        print(f"{name:28s} {len(df):>5} rows")
    lines = ["# Key findings", "", "Generated by `scripts/kpis.py` from the KPI query results.", ""]
    lines += [f"{i}. **{title}.** {text}" for i, (title, text) in enumerate(findings(k), 1)]
    (ROOT / "reports" / "key_findings.md").write_text("\n".join(lines) + "\n")
    print("wrote reports/key_findings.md")


if __name__ == "__main__":
    main()
